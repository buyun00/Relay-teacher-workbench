const { test, expect } = require('@playwright/test');
test('browse, warning filters, adaptation and personalized draft with answer separation', async ({page}) => {
  await page.goto('http://127.0.0.1:5178');
  await page.getByRole('button',{name:'题库与作业'}).click();
  await expect(page.getByText('共 2 题',{exact:true})).toBeVisible();
  await page.getByLabel('审核状态',{exact:true}).selectOption('needs_attention');
  await expect(page.getByText('共 1 题',{exact:true})).toBeVisible();
  await page.getByRole('button').filter({hasText:'图缺失'}).click();
  await expect(page.getByText('此题需要核对：missing_image：原图缺失')).toBeVisible();
  await page.getByLabel('审核状态',{exact:true}).selectOption('unreviewed');
  await page.getByRole('button').filter({hasText:'x = 1 是'}).click();
  await expect(page.frameLocator('iframe[title="题干预览"]').locator('math')).toHaveCount(2);
  await page.getByRole('button',{name:'改编此题',exact:true}).click();
  await page.getByLabel('题干',{exact:true}).fill('虚构改编：x = 2 是 x² = 4 的什么条件？');
  await page.getByLabel('改编原因').fill('虚构学生的双向判断练习');
  await page.getByRole('button',{name:'保存改编题'}).click();
  await page.getByRole('button',{name:'加入选题篮'}).click();
  await page.getByRole('button',{name:'选题篮 · 1'}).click();
  await page.getByLabel('学生',{exact:true}).selectOption('fictional-student');
  await page.getByLabel('练习目标与安排依据').fill('虚构教师确认：练习反向推理');
  await page.getByLabel('学生需要完成什么').fill('先只判断正向推导');
  await page.getByLabel('给学生的提示').fill('尝试 x = −2');
  await page.getByRole('button',{name:'生成并保存草稿'}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.frameLocator('iframe[title="学生版作业"]').locator('body')).toContainText('先只判断正向推导');
  await expect(page.frameLocator('iframe[title="学生版作业"]').locator('body')).not.toContainText('充分而不必要');
  await page.getByRole('button',{name:'教师版',exact:true}).click();
  await expect(page.frameLocator('iframe[title="教师版作业"]').locator('body')).toContainText('充分而不必要');
  await page.getByRole('button',{name:'关闭预览'}).click();
  await page.getByRole('button',{name:'作业草稿',exact:true}).click();
  await expect(page.getByRole('button',{name:/个性化练习.*草稿/})).toBeVisible();
});
